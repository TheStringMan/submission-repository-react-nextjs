const typeDefs = /* GraphQL */ `
  # author è una stringa (il nome), non un oggetto Author collegato:
  # rispecchia come i libri sono salvati davvero nell'array "books" sopra.
  type Book {
    title: String!
    published: Int!
    author: Author!
    id: String!
    genres: [String!]!
  }

  type Author {
    name: String!
    id: String!
    born: Int
    bookCount: Int!
  }

  type User {
    username: String!
    favoriteGenre: String!
    id: ID!
  }

  type Token {
    value: String!
  }

  # bookCount non esiste nei dati reali di "authors": va calcolato
  # (vedi il resolver Author.bookCount sotto), non lo fornisce il default resolver.
  type Mutation {
    addBook(
      title: String!
      author: String!
      published: Int!
      genres: [String!]!
    ): Book!
    editAuthor(name: String!, setBornTo: Int!): Author
    createUser(username: String!, favoriteGenre: String!): User
    login(username: String!, password: String!): Token
  }

  type Query {
    bookCount: Int!
    authorCount: Int!
    allBooks(author: String, genre: String): [Book!]!
    allAuthors: [Author!]!
    me: User
  }
`
module.exports = typeDefs
